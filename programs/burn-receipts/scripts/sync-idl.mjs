#!/usr/bin/env node
// Copies the IDL that `anchor build` writes (target/idl/burn_receipts.json) into the TypeScript client as a typed constant
// (src/lib/burnReceipts/idl.ts). The client's borsh coder, discriminators and account orders all come from this one file, and
// test/burnReceiptsClient.test.ts fails if the committed copy drifts from a fresh build.
import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const src = path.join(here, "..", "target", "idl", "burn_receipts.json");
const dst = path.join(here, "..", "..", "..", "src", "lib", "burnReceipts", "idl.ts");
const idl = JSON.parse(fs.readFileSync(src, "utf8"));
const body =
  "// GENERATED by programs/burn-receipts/scripts/sync-idl.mjs from target/idl/burn_receipts.json — do not edit by hand.\n" +
  "// Refresh after every program change: (cd programs/burn-receipts && anchor build && node scripts/sync-idl.mjs)\n" +
  'import type { AnchorIdl } from "@/lib/burnReceipts/idlTypes";\n\n' +
  `export const BURN_RECEIPTS_IDL: AnchorIdl = ${JSON.stringify(idl, null, 2)};\n`;
fs.writeFileSync(dst, body);
console.log(`wrote ${path.relative(process.cwd(), dst)} (${idl.instructions.length} instructions, address ${idl.address})`);
