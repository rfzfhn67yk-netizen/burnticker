#!/usr/bin/env node
// Copies the IDLs that `anchor build` writes into the TypeScript clients as typed constants:
//   target/idl/burn_receipts.json → src/lib/burnReceipts/idl.ts  (BURN_RECEIPTS_IDL)
//   target/idl/pair_curve.json    → src/lib/pairCurve/idl.ts     (PAIR_CURVE_IDL, 2026-10-10)
// Each client's borsh coder, discriminators and account orders all come from its one file, and test/burnReceiptsClient.test.ts /
// test/pairCurveClient.test.ts fail if a committed copy drifts from a fresh build. Sync from a DEFAULT-feature build (a `--features
// devnet` build writes devnet program ids into the IDL as PDA constants; docs/burnkeeper/devnet-run-log-2026-10-10.md finding 3).
import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const targets = [
  { idl: "burn_receipts.json", out: ["burnReceipts", "idl.ts"], name: "BURN_RECEIPTS_IDL" },
  { idl: "pair_curve.json", out: ["pairCurve", "idl.ts"], name: "PAIR_CURVE_IDL" },
];
for (const t of targets) {
  const src = path.join(here, "..", "target", "idl", t.idl);
  if (!fs.existsSync(src)) { console.log(`skip ${t.idl} (not built)`); continue; }
  const dst = path.join(here, "..", "..", "..", "src", "lib", ...t.out);
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  const idl = JSON.parse(fs.readFileSync(src, "utf8"));
  const body =
    `// GENERATED by programs/burn-receipts/scripts/sync-idl.mjs from target/idl/${t.idl} — do not edit by hand.\n` +
    "// Refresh after every program change: (cd programs/burn-receipts && anchor build && node scripts/sync-idl.mjs)\n" +
    'import type { AnchorIdl } from "@/lib/burnReceipts/idlTypes";\n\n' +
    `export const ${t.name}: AnchorIdl = ${JSON.stringify(idl, null, 2)};\n`;
  fs.writeFileSync(dst, body);
  console.log(`wrote ${path.relative(process.cwd(), dst)} (${idl.instructions.length} instructions, address ${idl.address})`);
}
