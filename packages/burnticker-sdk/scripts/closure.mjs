#!/usr/bin/env node
// The SDK's import closure (2026-10-09). Walks every import / export-from / dynamic import — TYPE-ONLY imports included, because the
// published package's .d.ts files need their sources too — from the package's entry points, resolving the repo's "@/…" alias and
// relative paths, and records (a) every repository file the package needs and (b) every npm package it needs.
//
//   node packages/burnticker-sdk/scripts/closure.mjs           print the closure
//   node packages/burnticker-sdk/scripts/closure.mjs --write   rewrite packages/burnticker-sdk/public-closure.json
//   node packages/burnticker-sdk/scripts/closure.mjs --check   exit 1 if public-closure.json is stale
//
// public-closure.json is the list the public-repo allowlist copies alongside packages/burnticker-sdk/; the leak test
// (test/burntickerSdkLeak.test.ts) asserts it is current, inside config/public-repo.allowlist, and clean under config/public-repo.denypatterns.
import fs from "node:fs";
import path from "node:path";
import { builtinModules } from "node:module";

export const PKG = path.resolve(import.meta.dirname, "..");
export const REPO = path.resolve(PKG, "../..");
export const MANIFEST = path.join(PKG, "public-closure.json");

const rel = (abs) => path.relative(REPO, abs).split(path.sep).join("/");

/** Entry points: the package's source and its examples. */
export function entries() {
  const out = [path.join(PKG, "src", "index.ts")];
  const ex = path.join(PKG, "examples");
  if (fs.existsSync(ex)) for (const f of fs.readdirSync(ex).sort()) if (/\.(ts|mts)$/.test(f)) out.push(path.join(ex, f));
  return out;
}

const SPEC_RE = /\b(?:import|export)\s+(?:type\s+)?(?:[\w*${}\s,]+?\s+from\s+)?["']([^"'\n]+)["']|\bimport\(\s*["']([^"'\n]+)["']\s*\)/g;

/** Import specifiers of a source file (comments stripped first so a commented-out import is not an edge). */
export function specifiers(src) {
  const code = src.replace(/\/\*[\s\S]*?\*\//g, "").split("\n").map((l) => (/^\s*\/\//.test(l) ? "" : l)).join("\n");
  const out = [];
  for (const m of code.matchAll(SPEC_RE)) out.push(m[1] ?? m[2]);
  return out;
}

/** Resolves a local specifier to a file, or returns { external } for a package / builtin. */
export function resolve(spec, from) {
  let base = null;
  if (spec.startsWith("@/")) base = path.join(REPO, "src", spec.slice(2));
  else if (spec.startsWith("./") || spec.startsWith("../")) base = path.resolve(path.dirname(from), spec);
  if (base === null) {
    if (spec.startsWith("node:") || builtinModules.includes(spec)) return { external: spec.startsWith("node:") ? spec : `node:${spec}` };
    const parts = spec.split("/");
    return { external: spec.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0] };
  }
  for (const c of [base, `${base}.ts`, `${base}.tsx`, `${base}.mts`, path.join(base, "index.ts")]) if (fs.existsSync(c) && fs.statSync(c).isFile()) return { file: c };
  throw new Error(`cannot resolve "${spec}" from ${rel(from)}`);
}

/** The closure: repo files (relative, sorted), npm packages and builtins (sorted), and every edge (for diagnostics). */
export function closure(starts = entries()) {
  const files = new Set(), externals = new Set(), edges = [];
  const queue = [...starts];
  while (queue.length) {
    const f = queue.shift();
    if (files.has(rel(f))) continue;
    files.add(rel(f));
    for (const s of specifiers(fs.readFileSync(f, "utf8"))) {
      const r = resolve(s, f);
      if (r.external) { externals.add(r.external); edges.push([rel(f), r.external]); }
      else { edges.push([rel(f), rel(r.file)]); queue.push(r.file); }
    }
  }
  return { files: [...files].sort(), externals: [...externals].sort(), edges };
}

/** The manifest as committed: package-internal files are implied by the package directory, so only files outside it are listed. */
export function manifest(c = closure()) {
  return {
    note: "Generated by packages/burnticker-sdk/scripts/closure.mjs --write. Repository files outside packages/burnticker-sdk/ that @burnticker/sdk imports (type-only imports included). The public-repo allowlist must carry these; test/burntickerSdkLeak.test.ts keeps this list current and private-free.",
    files: c.files.filter((f) => !f.startsWith("packages/burnticker-sdk/")),
    npm: c.externals.filter((e) => !e.startsWith("node:")),
    builtins: c.externals.filter((e) => e.startsWith("node:")),
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const m = manifest();
  const text = `${JSON.stringify(m, null, 2)}\n`;
  if (process.argv.includes("--write")) { fs.writeFileSync(MANIFEST, text); console.log(`wrote ${rel(MANIFEST)}: ${m.files.length} files, npm ${m.npm.join(", ")}`); }
  else if (process.argv.includes("--check")) { const cur = fs.existsSync(MANIFEST) ? fs.readFileSync(MANIFEST, "utf8") : ""; if (cur !== text) { console.error("public-closure.json is stale: run node packages/burnticker-sdk/scripts/closure.mjs --write"); process.exit(1); } console.log("public-closure.json is current"); }
  else console.log(text);
}
