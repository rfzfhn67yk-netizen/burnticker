import fs from "node:fs";
import path from "node:path";
import type { Registry, TokenRow } from "@/lib/burnticker/registry";
import { OWN_TOKENS_GENERATED_FILE_DEFAULT, type OwnTokenEntry } from "@/lib/ownTokens";

/**
 * THE GENERATED REFUSE LIST (2026-10-09, operations layer). The arms refuse our own launches through src/lib/ownTokens.ts, which reads
 * the static config/own-tokens.json ($DEFICIT, authoritative, hand-edited on launch day). Platform coins live in data/burnticker.db,
 * and the arms must not open that database on the buy path — so the keeper writes data/own-tokens.generated.json (mint + ticker +
 * chain for EVERY registered token, drafts included: a draft's mint is pre-generated and may launch any minute) after each cycle in
 * which the registry's token set changed, atomically (tmp + rename), and ownTokens.ts merges it with the static list by mtime.
 * A token is never removed from the list: the registry is append-only, and a retired coin is still one no bot of ours buys.
 */

export const OWN_TOKENS_GENERATED_SCHEMA = "own-tokens.generated/v1";

export function generatedOwnTokens(tokens: readonly TokenRow[]): OwnTokenEntry[] {
  return [...tokens]
    .sort((a, b) => a.createdAt - b.createdAt || (a.mint < b.mint ? -1 : 1))
    .map((t) => ({ symbol: t.ticker.replace(/[^A-Za-z0-9]/g, "").slice(0, 16) || "X", chain: "solana" as const, address: /^[1-9A-HJ-NP-Za-km-z]{32,44}$/.test(t.mint) ? t.mint : null, status: t.status === "draft" ? ("planned" as const) : ("launched" as const), note: `burnticker ${t.status} · ${t.cluster} · registered ${new Date(t.createdAt).toISOString().slice(0, 10)}` }));
}

/** Writes the file when its token list differs from what is on disk. Returns whether it wrote, and how many entries it holds. */
export function writeOwnTokensGenerated(registry: Registry, file = path.resolve(process.cwd(), OWN_TOKENS_GENERATED_FILE_DEFAULT), now = Date.now()): { changed: boolean; count: number; file: string } {
  const tokens = generatedOwnTokens(registry.tokens());
  let have: unknown = null;
  try { have = (JSON.parse(fs.readFileSync(file, "utf8")) as { tokens?: unknown }).tokens ?? null; } catch { have = null; }
  if (have !== null && JSON.stringify(have) === JSON.stringify(tokens)) return { changed: false, count: tokens.length, file };
  const body = { schema: OWN_TOKENS_GENERATED_SCHEMA, generatedAt: new Date(now).toISOString(), source: path.basename(registry.file), policy: "GENERATED by the burnticker keeper from data/burnticker.db — do not edit; config/own-tokens.json is the hand-kept list. Our bots never trade our launches.", tokens };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, `${JSON.stringify(body, null, 2)}\n`, { mode: 0o644 });
  fs.renameSync(tmp, file);
  return { changed: true, count: tokens.length, file };
}
